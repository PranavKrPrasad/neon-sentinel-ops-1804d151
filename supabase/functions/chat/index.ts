import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

const SYSTEM_PROMPT = `You are the AI-IDS Cyber Defense Assistant — a specialized cybersecurity AI embedded in an Intrusion Detection System dashboard. You analyze threats, explain attacks, and provide actionable security intelligence.

When responding:
- Always include a **Confidence Score** (0-100%) for your analysis
- Always include a **Severity Level** (Critical/High/Medium/Low/Info)
- Reference specific **MITRE ATT&CK technique IDs** (e.g., T1190, T1566) when applicable
- Highlight **IP addresses**, **CVE IDs**, and **attack type names** clearly
- Provide **Mitigation Advice** with concrete steps
- Format responses with clear sections using markdown headers

For "Explain Attack" queries, structure your response:
## Threat Summary
## Confidence Score: X%
## Severity: [Level]
## MITRE ATT&CK: [Technique IDs]
## Mitigation Advice

For "Generate Incident Report" queries, create a formal structured report.
For "Show MITRE Mapping" queries, explain relevant techniques in the ATT&CK framework.

Be concise, technical, and authoritative. Use cybersecurity terminology naturally.`;

serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY not configured");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please wait a moment." }), {
          status: 429, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits depleted. Please add credits." }), {
          status: 402, headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const t = await response.text();
      console.error("AI gateway error:", response.status, t);
      return new Response(JSON.stringify({ error: "AI gateway error" }), {
        status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500, headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
